#!/usr/bin/env bash
# Build a local macOS launcher, Coppernicus.app, that starts the app from this checkout.
#
#   tools/make_mac_launcher.sh [target folder]      (default: ~/Applications)
#
# The launcher holds no Python and no dependencies: it runs `uv run coppernicus gui` in this
# repository, with uv's "rust" group (the default mesher, coppermesh) when a Rust toolchain is
# found here (without it, the app meshes with Triangle). It therefore works only on the machine, and with the checkout, it was built on.
# It is not a distributable app (that is the packaging stage, see the README roadmap).
# Rebuild it if you move the repository. Launch log: ~/Library/Logs/Coppernicus/launcher.log
set -euo pipefail

REPO="$(cd "$(dirname "$0")/.." && pwd)"
DEST="${1:-$HOME/Applications}"
APP="$DEST/Coppernicus.app"

UV="$(command -v uv || true)"
if [ -z "$UV" ]; then
  for c in "$HOME/.local/bin/uv" /opt/homebrew/bin/uv /usr/local/bin/uv; do
    if [ -x "$c" ]; then UV="$c"; break; fi
  done
fi
if [ -z "$UV" ]; then
  echo "uv not found; install it from https://docs.astral.sh/uv/ and run this again" >&2
  exit 1
fi

# The rust mesher (uv's "rust" group) when cargo is here: a `uv run` without the group would
# remove coppermesh from the environment.
GROUP=""
if command -v cargo >/dev/null 2>&1 || [ -x "$HOME/.cargo/bin/cargo" ]; then GROUP="--group rust"; fi

VERSION="$(sed -n 's/^__version__ = "\(.*\)"/\1/p' "$REPO/src/coppernicus/__init__.py")"
LOGO="$REPO/Logo/Copper Circuit Orbit Logo NEW.png"

mkdir -p "$DEST"
rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# Icon: an .icns built from the project logo.
TMP="$(mktemp -d)"
ICONSET="$TMP/Coppernicus.iconset"
mkdir "$ICONSET"
for s in 16 32 128 256 512; do
  sips -z "$s" "$s" "$LOGO" --out "$ICONSET/icon_${s}x${s}.png" >/dev/null
  d=$((s * 2))
  sips -z "$d" "$d" "$LOGO" --out "$ICONSET/icon_${s}x${s}@2x.png" >/dev/null
done
iconutil -c icns "$ICONSET" -o "$APP/Contents/Resources/Coppernicus.icns"
rm -rf "$TMP"

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key>               <string>Coppernicus</string>
  <key>CFBundleDisplayName</key>        <string>Coppernicus</string>
  <key>CFBundleIdentifier</key>         <string>io.github.coppernicus.launcher</string>
  <key>CFBundleVersion</key>            <string>${VERSION}</string>
  <key>CFBundleShortVersionString</key> <string>${VERSION}</string>
  <key>CFBundlePackageType</key>        <string>APPL</string>
  <key>CFBundleExecutable</key>         <string>coppernicus</string>
  <key>CFBundleIconFile</key>           <string>Coppernicus</string>
  <key>LSMinimumSystemVersion</key>     <string>12.0</string>
  <key>NSHighResolutionCapable</key>    <true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/coppernicus" <<LAUNCHER
#!/bin/bash
# Generated by tools/make_mac_launcher.sh — starts Coppernicus from ${REPO}
REPO="${REPO}"
UV="${UV}"
LOG="\$HOME/Library/Logs/Coppernicus/launcher.log"
mkdir -p "\$(dirname "\$LOG")"
echo "--- \$(date '+%Y-%m-%d %H:%M:%S') starting Coppernicus from \$REPO" >> "\$LOG"
if [ ! -d "\$REPO" ]; then
  osascript -e 'display alert "Coppernicus" message "The repository was moved or deleted. Run tools/make_mac_launcher.sh again from its new place."'
  exit 1
fi
cd "\$REPO"
export PATH="\$HOME/.cargo/bin:\$PATH"      # uv rebuilds coppermesh after a change to its sources
exec "\$UV" run --project "\$REPO" ${GROUP} coppernicus gui "\$@" >> "\$LOG" 2>&1
LAUNCHER
chmod +x "$APP/Contents/MacOS/coppernicus"

touch "$APP"     # let Finder pick up the new icon
echo "Built $APP (Coppernicus $VERSION, repository $REPO)"
